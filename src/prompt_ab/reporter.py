from __future__ import annotations

import shutil
import textwrap
from datetime import datetime, timezone

from .client import CompletionResult


def _wrap(text: str, width: int) -> list[str]:
    if width < 10:
        width = 10
    lines: list[str] = []
    for paragraph in text.split("\n"):
        if paragraph == "":
            lines.append("")
        else:
            lines.extend(textwrap.wrap(paragraph, width=width) or [""])
    return lines or [""]


def print_side_by_side(a: CompletionResult, b: CompletionResult) -> None:
    term = shutil.get_terminal_size((80, 20))
    width = max(20, (term.columns - 4) // 2)
    head_a = f" Variant A ({a.model}) ".center(width, "=")
    head_b = f" Variant B ({b.model}) ".center(width, "=")
    lines_a = _wrap(a.text, width)
    lines_b = _wrap(b.text, width)
    print()
    print(f"{head_a}  {head_b}")
    print(f"{'-' * width}  {'-' * width}")
    for i in range(max(len(lines_a), len(lines_b))):
        la = lines_a[i] if i < len(lines_a) else ""
        lb = lines_b[i] if i < len(lines_b) else ""
        print(f"{la:<{width}}  {lb}")
    print(f"{'=' * width}  {'=' * width}")
    print()


def _md_cell(text: str) -> str:
    return text.replace("\n", "<br>").replace("|", "\\|")


def render_markdown(
    a: CompletionResult,
    b: CompletionResult,
    endpoint: str,
    model: str,
    temperature: float,
    max_tokens: int | None,
    system: str | None,
) -> str:
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    def block(text: str) -> str:
        return "```\n" + text + "\n```"

    lines = [
        "# Prompt A/B Test Results",
        "",
        f"- Generated: {now}",
        f"- Endpoint: {endpoint}",
        f"- Model: {model}",
        f"- Temperature: {temperature}",
        f"- Max tokens: {max_tokens if max_tokens is not None else '(default)'}",
        f"- System: {system if system else '(none)'}",
        "",
        "## Side by Side",
        "",
        "| Variant A | Variant B |",
        "|---|---|",
        f"| {_md_cell(a.text)} | {_md_cell(b.text)} |",
        "",
        "## Variant A",
        "",
        block(a.text),
        "",
        "## Variant B",
        "",
        block(b.text),
        "",
        "--",
        "",
        "Generated by prompt-ab from Asdale Dynamics, LLC.",
    ]
    return "\n".join(lines)
