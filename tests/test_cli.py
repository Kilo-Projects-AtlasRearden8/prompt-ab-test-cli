from __future__ import annotations

from pathlib import Path

from prompt_ab.cli import main


def test_cli_writes_markdown_report(mock_urlopen, tmp_path):
    _, state = mock_urlopen
    state["response_text"] = "variant output text"

    out = tmp_path / "report.md"
    argv = [
        "--prompt-a", "explain recursion",
        "--prompt-b", "explain recursion simply",
        "--endpoint", "http://example.com/v1",
        "--model", "mock-model",
        "--temperature", "0.7",
        "--output", str(out),
    ]
    assert main(argv) == 0

    md = out.read_text(encoding="utf-8")
    assert "# Prompt A/B Test Results" in md
    assert "## Side by Side" in md
    assert "## Variant A" in md
    assert "## Variant B" in md
    assert "variant output text" in md
    assert "http://example.com/v1" in md
    assert "mock-model" in md
    assert "Generated by prompt-ab from Asdale Dynamics, LLC." in md


def test_cli_missing_prompt_exits_nonzero():
    assert main(["--endpoint", "http://example.com/v1"]) == 1


def test_cli_connection_error_exits_nonzero(mock_urlopen):
    _, state = mock_urlopen
    from urllib.error import URLError
    state["raise"] = URLError
    state["raise_message"] = "connection refused"

    assert main(["--prompt-a", "hi", "--prompt-b", "there"]) == 1
